import type { Market } from "./team"

/** Where a homeowner is: marked, asked for a callback, heard the pitch, signed, or a serviced customer */
export type Lifecycle = "Lead" | "Callback" | "Pitched" | "Sold" | "Customer"

export type ContactEvent = {
  title: string
  /** The badge beside the title, for example "Signed". */
  status: string
  /** The status badge's dot class: bg-success, bg-warning or bg-muted-foreground/60. */
  dot: string
  /** Lucide icon in the timeline node: door-open, file-pen-line, spray-can, calendar, phone, message-square, file-text or sparkles. */
  icon: string
  text: string
  /** Team member id; always the contact's owner. */
  actorId: string
  /** Relative: "Yesterday", "2 days ago", "Last week", "Last month". */
  when: string
}

export type Contact = {
  /** The numeric id: /contacts/<id>. 1 to 40. */
  id: number
  name: string
  email: string
  /** The street address, under the name */
  address: string
  territoryId: string
  /** The territory's name, shown in the Territory column. */
  territory: string
  office: Market
  /** Team member id: the rep who sold or is working the home, or partner relations. */
  ownerId: string
  lifecycle: Lifecycle
  /** The Last Activity column: a Lucide icon and the relative time. */
  lastActivity: { icon: string; when: string }
  /** Open deals: count, exact dollars (the contact page's big figure), and as the list prints it ($1,039); null when none. */
  openDeals: { count: number; amount: number; short: string | null }
  /** The contact page's Activity timeline, newest first. */
  activity: ContactEvent[]
}

